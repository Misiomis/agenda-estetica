export const ORDEN_PLANTILLAS_HIFU = ['facial_antes', 'facial_despues', 'corporal_antes', 'corporal_despues'];

// Arma el mensaje final para una paciente: el mismo prefijo de
// personalización que ya usan el resto de las recomendaciones de este panel
// (nombre real si se conoce, encabezado neutro si no), seguido del texto
// exacto de la plantilla — nunca se reescribe el contenido clínico.
export function construirMensajeHifu(clave, nombrePaciente) {
  const plantilla = PLANTILLAS_HIFU[clave];
  if (!plantilla) throw new Error('Plantilla HIFU desconocida: ' + clave);
  const nombre = (nombrePaciente || '').toString().trim();
  const prefijo = nombre ? `Recomendaciones para ${nombre}` : 'Recomendaciones posteriores a tu sesión';
  return `${prefijo}\n\n${plantilla.texto}`;
}
